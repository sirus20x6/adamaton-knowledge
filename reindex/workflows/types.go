// Package workflows holds the Temporal workflow definitions for the
// arxiv reindex subsystem. Activities live in
// github.com/sirus20x6/adamomaton-knowledge/reindex/activities; the worker binary that
// registers them lives in cmd/reindex-worker.
//
// The two workflows mirror the bash loop in
// dashboard/reindex-arxiv-latex/reindex-arxiv-latex.sh:
//
//	ReindexArxivCorpusWorkflow — replaces the outer "while read line" loop
//	ReindexArxivPaperWorkflow  — replaces the per-paper body (lines 64-173)
//
// Concurrent fan-out replaces the bash's strictly-serial per-paper
// execution; per-paper deterministic IDs replace the inflight-marker
// file. Temporal history is the inflight log.
package workflows

import "time"

// Task queues. Split (2026-05-14) so ingest activities can't be
// starved by slow LLM-bound extract retries. The ingest queue carries
// the corpus + paper workflows and their CPU/parser-bound activities;
// the extract queue carries the long-running ExtractCorpusWorkflow
// daemon and its LLM-bound ExtractEntities activity. Each queue has
// its own MaxConcurrentActivityExecutionSize on the worker side, so
// extract retry-storms (e.g. vLLM offline) leave ingest unaffected.
const (
	TaskQueueIngest  = "reindex-ingest"
	TaskQueueExtract = "reindex-extract"
)

// Workflow names. The dashboard (or a future CLI) calls ExecuteWorkflow
// by string to avoid importing this package.
const (
	WorkflowReindexCorpus = "ReindexArxivCorpusWorkflow"
	WorkflowReindexPaper  = "ReindexArxivPaperWorkflow"
	WorkflowExtractCorpus = "ExtractCorpusWorkflow"
)

const QueryProgress = "progress"
const QueryExtractProgress = "extract_progress"

// ReindexArxivCorpusInput drives the parent workflow. Concurrency caps
// how many child workflows run in parallel; the bash script ran one at
// a time, so 4 is a conservative-but-faster default for the Pi.
type ReindexArxivCorpusInput struct {
	// Concurrency caps simultaneous per-paper workflows. <=0 → default 4.
	Concurrency int `json:"concurrency,omitempty"`
	// DryRun=true skips the actual platform POST and just reports what
	// would have been reindexed. Useful for verifying the SQL filter.
	DryRun bool `json:"dry_run,omitempty"`
	// Limit caps the work-set size. <=0 → no cap (full corpus).
	Limit int `json:"limit,omitempty"`
	// ContinueAsNewEvery caps how many papers a single workflow run
	// processes before ContinueAsNew. <=0 means default 500. Set high
	// (e.g. 10000) to disable for small one-off runs.
	ContinueAsNewEvery int `json:"continue_as_new_every,omitempty"`
	// Carry, when non-nil, holds accumulated counters from a prior
	// workflow run that ContinueAsNew'd into us. Set by the workflow
	// itself, never by external callers.
	Carry *CorpusProgress `json:"carry,omitempty"`
}

// CorpusProgress is what the QueryProgress handler returns. InFlight
// is the list of arxiv_ids currently being processed by child workflows.
type CorpusProgress struct {
	Total     int      `json:"total"`
	Done      int      `json:"done"`
	Skipped   int      `json:"skipped"`
	Failed    int      `json:"failed"`
	InFlight  []string `json:"in_flight"`
	StartedAt time.Time `json:"started_at"`
}

// ReindexArxivPaperInput is the child workflow's input. OldDocID is
// the existing deepresearch.documents row that will be replaced; the
// new document ID is generated by the workflow (UUID via SideEffect
// for replay determinism).
type ReindexArxivPaperInput struct {
	ArxivID  string `json:"arxiv_id"`
	OldDocID string `json:"old_doc_id"`
	Title    string `json:"title,omitempty"`
	DryRun   bool   `json:"dry_run,omitempty"`
}

// PaperResult is the return value from a per-paper workflow. Skipped
// covers the cases the bash script handled with "skip_no_latex" /
// "skip_invalid" — the paper is not retried but the parent counts it
// against Skipped, not Failed.
type PaperResult struct {
	ArxivID     string `json:"arxiv_id"`
	NewDocID    string `json:"new_doc_id,omitempty"`
	SourceTier  string `json:"source_tier,omitempty"`
	FigureCount int    `json:"figure_count,omitempty"`
	SizeBytes   int64  `json:"size_bytes,omitempty"`
	Skipped     bool   `json:"skipped,omitempty"`
	SkipReason  string `json:"skip_reason,omitempty"`
}

// ExtractCorpusInput drives the ExtractCorpusWorkflow sweep. The
// workflow runs indefinitely, periodically scanning the corpus for
// docs whose ingest is finished but whose graph extraction hasn't
// landed, then firing R2R's /v3/documents/{id}/extract endpoint for
// each. Decoupled from the reindex pipeline so paper throughput
// isn't gated on extract latency, and so the existing backlog of
// already-eprint docs gets picked up the same way as fresh ones.
type ExtractCorpusInput struct {
	// CorpusID is the platform.corpora UUID to sweep. Required.
	CorpusID string `json:"corpus_id"`
	// Concurrency caps simultaneous in-flight ExtractEntities activities.
	// R2R queues extracts internally so the call itself is cheap, but
	// each extract spawns LLM work on the backend; keep this low.
	// <=0 → default 2.
	Concurrency int `json:"concurrency,omitempty"`
	// BatchSize caps how many doc IDs the QueryReadyForExtraction
	// activity returns per pass. <=0 → default 50.
	BatchSize int `json:"batch_size,omitempty"`
	// SleepBetweenSeconds is the gap between batches when the work-set
	// query returns nothing (i.e. we've drained the current ready
	// queue and need to wait for more docs to finish ingesting). <=0
	// → default 60s.
	SleepBetweenSeconds int `json:"sleep_between_seconds,omitempty"`
	// ContinueAsNewEvery caps docs settled per workflow run before
	// ContinueAsNew. <=0 → default 500.
	ContinueAsNewEvery int `json:"continue_as_new_every,omitempty"`
	// Carry accumulates counters across continuations. Operators never
	// set this; the workflow plumbs it through itself.
	Carry *ExtractProgress `json:"carry,omitempty"`
}

// ExtractProgress is the query-visible state for ExtractCorpusWorkflow.
// Triggered counts docs we sent an /extract POST for; Succeeded is the
// subset that flipped to extraction_status='success'. Failed is the
// activity-level error count (HTTP failures).
type ExtractProgress struct {
	Triggered int       `json:"triggered"`
	Succeeded int       `json:"succeeded"`
	Failed    int       `json:"failed"`
	LastSweep time.Time `json:"last_sweep"`
	StartedAt time.Time `json:"started_at"`
}

// ArxivPaper is a single row in the work-set returned by QueryWorkSet.
// Carries enough state for the per-paper workflow to operate without
// re-querying the deepresearch postgres.
type ArxivPaper struct {
	ArxivID  string `json:"arxiv_id"`
	OldDocID string `json:"old_doc_id"`
	Title    string `json:"title"`
}
